function Basics() {
  return (
    <>
      <Lead>
        Один игрок — детектив, другой — убийца. Убийца тайно играет за одного из жителей города и
        убивает по собственному мотиву. Детектив не знает ни кто убийца, ни зачем он убивает, и
        должен назвать и то, и другое.
      </Lead>

      <Head>Как выиграть</Head>
      <Item title="Детектив">
        Назвать профессию убийцы и его мотив. Обвинение одно на партию: ошибка в любом из двух
        пунктов — поражение. Если прошло {MAX_ROUNDS} раундов, а убийца не добрался до{' '}
        {KILLS_TO_WIN} жертв, побеждает детектив.
      </Item>
      <Item title="Убийца">
        Довести число жертв до {KILLS_TO_WIN}. После пятого убийства детектив ещё может спросить
        по оставшимся жетонам слежки, а потом обязан назвать убийцу — если не угадает, убийца
        победил.
      </Item>

      <Head>Круг хода</Head>
      <Item title="1 · Ночь">
        Убийца выбирает жертву и пугает {SCARES_PER_NIGHT} жителей. Детектив в это время не видит
        ничего.
      </Item>
      <Item title="2 · Место преступления">
        Детектив расселяет жителей с района, где произошло убийство, по соседним районам.
      </Item>
      <Item title="3 · День">
        Детектив ездит по городу, допрашивает жителей и пользуется зданиями.
      </Item>
      <Item title="4 · Город">
        Сначала убийца, потом детектив тянут жетон случайной группы жителей и двигают её людей —
        каждого на один район. Город живёт своей жизнью, и следы смещаются.
      </Item>

      <Head>Город</Head>
      <Item title="Карта">
        4 × 4 района, 20 жителей. В одном районе не может стоять больше{' '}
        {MAX_CITIZENS_PER_DISTRICT} живых жителей.
      </Item>
      <Item title="Житель">
        У каждого есть профессия, группа (творческие, рабочие, служащие и так далее) и четыре
        признака: пол, возраст, телосложение, рост. Именно по этим признакам детектив и ищет
        убийцу.
      </Item>
    </>
  );
}

function DetectiveRules() {
  return (
    <>
      <Lead>
        Вы ищете человека по четырём признакам и по картине убийств. Вопросы задаёте жителям — но
        убийца отвечает за них и может лгать.
      </Lead>

      <Head>Ход детектива</Head>
      <Item title="2 перемещения">
        Машина переезжает в соседний район. Где стоит машина — там ночью убивать нельзя, это ваша
        защита.
      </Item>
      <Item title="2 действия">
        Действие — это либо допрос, либо использование здания. Выбор за вами: два допроса, два
        здания или по одному.
      </Item>
      <Item title="Допрос">
        Спрашивать можно только жителей из района с машиной, и только одного района за ход.
        Вопрос — про один признак: «убийца — мужчина?», «убийце 40?». Ответ «да» или «нет».
      </Item>
      <Item title="Одного жителя — один раз за ход">
        Потратить оба действия на одного и того же человека нельзя. Со следующего хода его можно
        спрашивать снова, а обойти запрет сразу позволяет только закусочная.
      </Item>

      <Head>Кому верить</Head>
      <Item title="Обычный житель">
        Отвечает честно всегда — игра не позволит соврать за него.
      </Item>
      <Item title="Убийца и его группа-помощник" tone="danger">
        Могут лгать. Кто именно — вы не знаете, в этом и состоит задача.
      </Item>
      <Item title="Жетон слежки" tone="police">
        Ответ жителя под жетоном — всегда честный, даже если это сам убийца. Жетоны не тратят
        действия: спрашивать по ним можно сколько угодно раз за ход.
      </Item>

      <Head>Подсказки</Head>
      <Item title="Журнал">
        Все вопросы и ответы собраны во вкладке «Журнал» вместе с таблицей подозреваемых. Честные
        ответы по жетонам помечены отдельно. Если ответы противоречат друг другу, кто-то солгал:
        отметьте сомнительный ответ «не верю» — таблица перестанет его учитывать. Свой фильтр
        подсвечивает жителей по признакам и группам, которые вы выберете.
      </Item>
      <Item title="Мотивы">
        Шесть кандидатов видны с первого хода, настоящий — один. Вычёркивайте те, что не сходятся
        с картиной убийств: где убийца бил, а где не стал.
      </Item>
      <Item title="Запуганный житель">
        Молчит и не отвечает на вопросы. Снять испуг можно в больнице.
      </Item>
    </>
  );
}

function KillerRules() {
  return (
    <>
      <Lead>
        Вы — один из жителей города. Внешне обычный человек: ходите вместе со всеми, отвечаете на
        допросах. Ваша задача — довести счёт до {KILLS_TO_WIN} жертв и не попасться.
      </Lead>

      <Head>Начало партии</Head>
      <Item title="Группа-помощник">
        Пока детектив ставит машину, вы выбираете помощников из трёх случайных групп. Детектив не
        знает ни вашего выбора, ни того, из чего вы выбирали. Без выбора первая ночь не начнётся.
      </Item>

      <Head>Ночь</Head>
      <Item title="Убийство по мотиву">
        Убивать можно только тех, кого разрешает ваш мотив. Мотив — не подсказка, а закон: нарушить
        его нельзя.
      </Item>
      <Item title="Где нельзя убивать" tone="danger">
        В районе с полицейской машиной. И себя убить тоже нельзя.
      </Item>
      <Item title="Можно не убивать">
        Один раз за партию вы вправе отказаться от убийства — например, когда любая жертва
        выдала бы ваш мотив. Второй отказ означает поражение.
      </Item>
      <Item title={`Испуг · ${SCARES_PER_NIGHT} жителя`}>
        Запуганный житель не отвечает на допросах. Так закрывают рот тем, кто стоит рядом с
        машиной детектива.
      </Item>

      <Head>Допрос</Head>
      <Item title="За кого вы лжёте">
        За себя и за свою группу-помощника. За остальных отвечаете честно — иначе ход не пройдёт.
      </Item>
      <Item title="Не противоречьте себе" tone="danger">
        Детектив ведёт журнал. Два разных ответа на один и тот же вопрос выдают лжеца вернее, чем
        любая улика. Держите в голове один непротиворечивый портрет — и пусть он указывает на
        кого-то другого.
      </Item>
      <Item title="Жетон слежки" tone="police">
        Если на жителе лежит жетон, вы обязаны ответить честно. Даже за себя.
      </Item>

      <Head>Фаза Города</Head>
      <Item title="Движение групп">
        Вы тянете жетон случайной группы и двигаете её жителей — каждого на один район. Уводите
        своих подальше от машины, а чужих подставляйте под неё.
      </Item>
    </>
  );
}

function Buildings() {
  return (
    <>
      <Lead>
        В районах стоят здания. Использовать можно только то, что находится в районе с машиной, и
        каждое здание — не больше одного раза за ход. Это действие, их всего два за ход.
      </Lead>

      <Item title="Полицейский участок" tone="police">
        Положить жетон слежки на жителя. Под жетоном житель отвечает честно всегда — даже если это
        убийца. Спрашивать по жетону можно бесплатно в любой момент дня — и после пятого
        убийства, пока обвинение не предъявлено.
      </Item>
      <Item title="Больница">
        Снять испуг с жителя. Запуганный молчит, а вылеченный снова отвечает на вопросы.
      </Item>
      <Item title="Пожарная часть">
        Подвинуть жителей одной выбранной группы — каждого на один район. Способ собрать нужных
        людей вокруг машины.
      </Item>
      <Item title="Закусочная">
        Допросить жителя из соседнего района, не подъезжая к нему. Единственный способ спросить
        человека, до которого не дотянулась машина, — и единственный способ вернуться к тому,
        кого вы уже допрашивали в этот ход.
      </Item>
    </>
  );
}

function Lead({ children }: { children: React.ReactNode }) {
  return (
    <p
      style={{
        margin: '0 0 18px',
        fontSize: 13,
        lineHeight: 1.6,
        color: 'oklch(0.76 0.014 80)'
      }}
    >
      {children}
    </p>
  );
}

function Head({ children }: { children: React.ReactNode }) {
  return (
    <div
      style={{
        fontFamily: FONT.mono,
        fontSize: 9.5,
        letterSpacing: '0.24em',
        color: P.gold,
        margin: '22px 0 10px'
      }}
    >
      {children}
    </div>
  );
}

const TONES = {
  plain: 'oklch(0.34 0.016 55)',
  danger: 'oklch(0.45 0.1 27)',
  police: 'oklch(0.45 0.08 250)'
} as const;

function Item({
  title,
  tone = 'plain',
  children
}: {
  title: string;
  tone?: keyof typeof TONES;
  children: React.ReactNode;
}) {
  return (
    <div style={{ display: 'flex', gap: 11, marginBottom: 13 }}>
      <span style={{ width: 2, flexShrink: 0, borderRadius: 2, background: TONES[tone] }} />
      <div style={{ minWidth: 0 }}>
        <div
          style={{
            fontFamily: FONT.display,
            fontSize: 17,
            fontWeight: 700,
            textTransform: 'uppercase',
            lineHeight: 1.05,
            color: P.ink,
            marginBottom: 4
          }}
        >
          {title}
        </div>
        <div style={{ fontSize: 12.5, lineHeight: 1.55, color: 'oklch(0.68 0.014 80)' }}>
          {children}
        </div>
      </div>
    </div>
  );
}
